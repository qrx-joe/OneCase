import { randomUUID } from 'node:crypto'
import { test, expect, type APIRequestContext } from '@playwright/test'
import resetDemoData from './reset'

test.use({ timezoneId: 'Asia/Shanghai' })
test.beforeAll(() => resetDemoData())
const plan = { serviceType: 'EMPLOYMENT', subjectRef: 'SYN-P01', subjectConfirmed: true, consent: 'CONFIRMED', goal: '合成白班就业指导', owner: '合成甲', nextAction: '联系对象核对服务进展', nextActionAt: '2026-10-10T01:00:00.000Z', referralTo: '合成服务站' }
async function get(request: APIRequestContext, id: string) {
  const res = await request.get(`/api/services/${id}`)
  expect(res.status()).toBe(200)
  return (await res.json()).data
}
async function create(request: APIRequestContext, title: string, extra = {}) {
  const res = await request.post('/api/services', { data: { clientKey: randomUUID(), title, rawText: '仅用于自动回归的合成记录', plan: { ...plan, ...extra } } })
  expect(res.status()).toBe(200)
  const id: string = (await res.json()).data.id
  const c = await get(request, id)
  expect((await request.post(`/api/cases/${id}/status`, { data: { expectedVersion: c.version, status: 'IN_PROGRESS' } })).status()).toBe(200)
  return id
}
async function event(request: APIRequestContext, id: string, kind: string, extra = {}) {
  const c = await get(request, id)
  const res = await request.post(`/api/services/${id}`, { data: { expectedVersion: c.version, kind, note: '合成服务进展', ...extra } })
  expect(res.status()).toBe(200)
}

