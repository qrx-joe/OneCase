test('人工接续沿用原约定日期，保存后提示消退且旧结果保持历史', async ({ page, request }) => {
  const id = await create(request, '合成接续探访', { serviceType: 'VISIT', subjectRef: 'SYN-P03', owner: '合成丙', goal: '合成本次日常探访及后续安排' })
  await event(request, id, 'SERVICE_PROVIDED')
  await event(request, id, 'RESULT_CONFIRMED', { evidence: '合成对象本人反馈', followUpAt: '2026-10-28T01:00:00.000Z' })
  const old = await get(request, id)
  expect((await request.post(`/api/cases/${id}/status`, { data: { expectedVersion: old.version, status: 'RESOLVED' } })).status()).toBe(200)
  await page.clock.setFixedTime(new Date('2026-10-10T02:00:00.000Z'))
  await page.goto(`/services?caseId=${id}`)
  await page.getByRole('button', { name: '开启新一轮服务', exact: true }).click()
  await expect(page.getByLabel('约定行动时间', { exact: true })).toHaveValue('2026-10-28T09:00')
  await expect(page.getByLabel('服务意愿', { exact: true })).toHaveValue('UNKNOWN')
  const worklist = page.getByRole('complementary', { name: '待办与回访' })
  await worklist.getByLabel('按负责人筛选').selectOption('合成丙')
  await expect(worklist.getByRole('button', { name: '待接续 1', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '人工确认并创建服务计划', exact: true }).click()
  await expect(page.getByRole('button', { name: '保存计划', exact: true })).toBeVisible()
  await expect(worklist.getByRole('button', { name: '待接续 0', exact: true })).toBeVisible()
  const items = (await (await request.get('/api/services')).json()).data
  const child = items.find((c: { service: { previousCaseId: string | null } }) => c.service.previousCaseId === id)
  expect(child.service).toMatchObject({ resultStatus: 'UNKNOWN', plan: { consent: 'UNKNOWN', nextActionAt: '2026-10-28T01:00:00.000Z' } })
  expect((await get(request, id))).toMatchObject({ status: 'RESOLVED', service: { resultStatus: 'CONFIRMED', followUpAt: '2026-10-28T01:00:00.000Z' } })
  await page.reload()
  await worklist.getByLabel('按负责人筛选').selectOption('合成丙')
  await expect(worklist.getByRole('button', { name: '待接续 0', exact: true })).toBeVisible()
  await worklist.getByRole('button', { name: '未来安排 1', exact: true }).click()
  await expect(worklist.getByRole('button', { name: /探访关爱：新一轮跟进/ })).toContainText('2026/10/28')
  await worklist.getByRole('button', { name: '全部事项 2', exact: true }).click()
  await worklist.getByRole('button', { name: /合成接续探访/ }).click()
  await expect(page.getByText('已有关联后续事项，进展请查看新事项。', { exact: false })).toBeVisible()
})
